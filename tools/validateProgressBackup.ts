import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createProgressBackup, restoreProgressBackup } from "../src/app/progressBackup.ts";

const root = mkdtempSync(join(tmpdir(), "apogee-backup-test-"));
const source = join(root, "profile"), target = join(root, "backups");
mkdirSync(source);
assert.throws(() => createProgressBackup(source, target), /no saved progress/);
console.log("PASS empty profile reports that there is nothing to back up");
const expected = ["admin-overrides.json", "expedition-first-light-v5.json", "ghost.json", "quests.json", "settings.json"];
for (const file of expected) writeFileSync(join(source, file), JSON.stringify({ file, progress: 42 }));
writeFileSync(join(source, "session.json"), "secret-token");
mkdirSync(join(source, "Local Storage"));
const first = createProgressBackup(source, target);
assert.deepEqual(first.files, expected);
assert.deepEqual(readdirSync(first.folder).sort(), ["RESTORE.txt", ...expected].sort());
for (const file of expected) assert.equal(readFileSync(join(first.folder, file), "utf8"), readFileSync(join(source, file), "utf8"));
assert.match(readFileSync(join(first.folder, "RESTORE.txt"), "utf8"), /quit Apogee/);
console.log("PASS every portable save copied byte-for-byte with restore instructions; session and cache excluded");
const second = createProgressBackup(source, target);
assert.notEqual(second.folder, first.folder);
assert.equal(readFileSync(join(first.folder, "quests.json"), "utf8"), readFileSync(join(source, "quests.json"), "utf8"));
console.log("PASS repeated backup preserves the previous backup");
const blocked = join(root, "not-a-directory");
writeFileSync(blocked, "occupied");
assert.throws(() => createProgressBackup(source, blocked));
console.log("PASS unwritable destination reports failure");

const restoredProfile = join(root, "restored");
mkdirSync(restoredProfile);
writeFileSync(join(restoredProfile, "quests.json"), '{"old":true}');
writeFileSync(join(restoredProfile, "session.bin"), "keep-this-session");
const restored = restoreProgressBackup(first.folder, restoredProfile);
assert.deepEqual(restored.files, expected);
assert(restored.previous);
assert.equal(readFileSync(join(restored.previous!, "quests.json"), "utf8"), '{"old":true}');
assert.equal(JSON.parse(readFileSync(join(restoredProfile, "quests.json"), "utf8")).progress, 42);
const settings = JSON.parse(readFileSync(join(restoredProfile, "settings.json"), "utf8"));
assert.equal(settings.statsDir, null); assert.equal(settings.window, null);
assert.equal(readFileSync(join(restoredProfile, "session.bin"), "utf8"), "keep-this-session");
console.log("PASS restore copies progress, preserves prior saves and session, resets machine-specific paths");
const bad = join(root, "bad-backup"); mkdirSync(bad);
writeFileSync(join(bad, "quests.json"), '{"changed":true}');
writeFileSync(join(bad, "settings.json"), "broken-json");
const before = readFileSync(join(restoredProfile, "quests.json"), "utf8");
assert.throws(() => restoreProgressBackup(bad, restoredProfile));
assert.equal(readFileSync(join(restoredProfile, "quests.json"), "utf8"), before);
assert.throws(() => restoreProgressBackup(source + "-missing", restoredProfile));
console.log("PASS corrupt and missing backups fail before replacing current progress");
