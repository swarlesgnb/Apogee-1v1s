/**
 * Write the Shadow score table: every Season 1 scenario's committed board points.
 *
 *   npm run build:shadows              rebuild from the season's committed files
 *   npm run build:shadows -- --check   fail if either output is stale
 *
 * Re-run after build:season, recalibrate:season or a recut changes a threshold;
 * validate:queue fails until it is. What each point is and where it comes from is in
 * src/core/match/shadowSource.ts.
 *
 * Two files from one table. data/shadow_scores.json is the record a person reads;
 * src/core/match/shadowScores.ts carries the same numbers as a module, because the Edge
 * Functions import core modules and nothing in them imports JSON.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { buildShadowScores, type ShadowBuild } from "../src/core/match/shadowSource.ts";
import type { ShadowScoreTable } from "../src/core/match/shadow.ts";

const root = new URL("../", import.meta.url);
const read = (path: string) => JSON.parse(readFileSync(new URL(path, root), "utf8"));
export const SHADOW_TABLE_PATH = fileURLToPath(new URL("data/shadow_scores.json", root));
export const SHADOW_MODULE_PATH = fileURLToPath(new URL("src/core/match/shadowScores.ts", root));

export function buildFromRepo(): ShadowBuild {
  return buildShadowScores(read("data/seasons/season-1.json"), read("data/season-1/families.json"), read("data/pool.json"));
}

export function tableJson(table: ShadowScoreTable): string {
  return JSON.stringify(table, null, 1) + "\n";
}

/** The module the server imports: the table, verbatim, with a header saying where it came from. */
export function shadowModule(table: ShadowScoreTable): string {
  return "/**\n * Generated by tools/buildShadowTable.ts from data/shadow_scores.json. Do not edit by hand:\n" +
    " * run npm run build:shadows. The Edge Functions read the Shadow table from here because\n" +
    " * they import core modules and never JSON.\n */\n\n" +
    'import type { ShadowScoreTable } from "./shadow.ts";\n\n' +
    `export const SHADOW_SCORES: ShadowScoreTable = ${JSON.stringify(table)};\n`;
}

function main(): void {
  const { table, skippedMedians } = buildFromRepo();
  if (process.argv.includes("--check")) {
    const jsonOk = existsSync(SHADOW_TABLE_PATH) && readFileSync(SHADOW_TABLE_PATH, "utf8") === tableJson(table);
    const moduleOk = existsSync(SHADOW_MODULE_PATH) && readFileSync(SHADOW_MODULE_PATH, "utf8") === shadowModule(table);
    console.log(jsonOk ? "OK: data/shadow_scores.json matches the season's committed numbers" : "FAIL: data/shadow_scores.json is stale; run npm run build:shadows");
    console.log(moduleOk ? "OK: src/core/match/shadowScores.ts matches it" : "FAIL: src/core/match/shadowScores.ts is stale; run npm run build:shadows");
    if (!jsonOk || !moduleOk) process.exit(1);
    return;
  }
  writeFileSync(SHADOW_TABLE_PATH, tableJson(table));
  writeFileSync(SHADOW_MODULE_PATH, shadowModule(table));
  const rows = Object.values(table.scenarios);
  console.log(`wrote data/shadow_scores.json and src/core/match/shadowScores.ts: ${rows.length} scenarios`);
  for (const w of [...new Set(rows.map((r) => r.window))].sort()) {
    const inWindow = rows.filter((r) => r.window === w);
    const lo = Math.max(...inWindow.map((r) => r.points[0][0]));
    const hi = Math.min(...inWindow.map((r) => r.points[r.points.length - 1][0]));
    console.log(`  window ${w}: ${inWindow.length} scenarios, every one covers percentiles ${lo} to ${hi}`);
  }
  if (skippedMedians.length) console.log(`  median left out on ${skippedMedians.length}: ${skippedMedians.slice(0, 5).map((s) => `${s.scenario} (${s.why})`).join("; ")}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
